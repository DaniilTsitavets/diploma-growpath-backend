import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    Computed,
    DateTime,
    ForeignKey,
    Index,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base

SEARCH_VECTOR = (
    "setweight(to_tsvector('english', heading), 'A') || "
    "setweight(to_tsvector('english', body), 'B')"
)


class KbDocumentModel(Base):
    """One knowledge-base file; `species` NULL means general care."""

    __tablename__ = "kb_documents"
    __table_args__ = (
        CheckConstraint("slug ~ '^[a-z0-9-]{1,64}$'", name="slug"),
        CheckConstraint("source_url LIKE 'https://%'", name="source_url"),
        CheckConstraint("content_sha256 ~ '^[0-9a-f]{64}$'", name="sha"),
        CheckConstraint(
            "btrim(title) <> '' AND char_length(title) <= 200 AND char_length(species) <= 100"
            " AND char_length(source_title) <= 300 AND char_length(source_url) <= 1000",
            name="lengths",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    slug: Mapped[str] = mapped_column(unique=True)
    title: Mapped[str]
    species: Mapped[str | None]
    source_title: Mapped[str]
    source_url: Mapped[str]
    content_sha256: Mapped[str]
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class KbSectionModel(Base):
    """A section of a document; `search_vector` is generated by the database."""

    __tablename__ = "kb_sections"
    __table_args__ = (
        UniqueConstraint("document_id", "position", name="uq_kb_sections_document_position"),
        UniqueConstraint("document_id", "anchor", name="uq_kb_sections_document_anchor"),
        CheckConstraint("position >= 1", name="position"),
        CheckConstraint(
            "btrim(heading) <> '' AND char_length(heading) <= 200"
            " AND btrim(body) <> '' AND char_length(body) <= 4000",
            name="lengths",
        ),
        Index("ix_kb_sections_search_vector", "search_vector", postgresql_using="gin"),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    document_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("kb_documents.id"))
    position: Mapped[int]
    anchor: Mapped[str]
    heading: Mapped[str]
    body: Mapped[str]
    # The design declares the generated column without NOT NULL.
    search_vector: Mapped[str] = mapped_column(
        TSVECTOR, Computed(SEARCH_VECTOR, persisted=True), nullable=True
    )
