import uuid
from datetime import datetime

from sqlalchemy import CheckConstraint, DateTime, Index, func
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base

STATUS_CHECK = "status IN ('reserved', 'committed', 'released')"
EXPIRY_CHECK = "expires_at > created_at"


class ReservationColumns:
    user_id: Mapped[uuid.UUID]
    status: Mapped[str] = mapped_column(server_default="reserved")
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class AiQuotaReservation(ReservationColumns, Base):
    """One paid diagnosis attempt; the id is generated by plant-care for every attempt."""

    __tablename__ = "ai_quota_reservations"
    __table_args__ = (
        CheckConstraint(STATUS_CHECK, name="status"),
        CheckConstraint(EXPIRY_CHECK, name="expiry"),
        Index("ix_ai_quota_reservations_user_created", "user_id", "created_at"),
    )

    reservation_id: Mapped[uuid.UUID] = mapped_column(primary_key=True)


class ExpertQuotaReservation(ReservationColumns, Base):
    """One expert escalation, keyed by the escalation id of plant-care."""

    __tablename__ = "expert_quota_reservations"
    __table_args__ = (
        CheckConstraint(STATUS_CHECK, name="status"),
        CheckConstraint(EXPIRY_CHECK, name="expiry"),
        Index("ix_expert_quota_reservations_user_created", "user_id", "created_at"),
    )

    escalation_id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
